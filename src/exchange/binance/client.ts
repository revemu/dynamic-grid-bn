/**
 * Calculates decimal precision (number of decimal places) from a step or tick size.
 */
export function getPrecision(val: number): number {
  if (!val || val >= 1) return 0;
  const str = val.toString();
  if (str.includes("e-")) {
    const parts = str.split("e-");
    return parseInt(parts[1], 10);
  }
  const decimalPart = str.split(".")[1];
  return decimalPart ? decimalPart.length : 0;
}

/**
 * Formats a quantity down to stepSize and precision without exponential notation.
 */
export function roundToStep(qty: number, stepSize: number, precision?: number): number {
  if (!stepSize || stepSize <= 0) return qty;
  const p = precision ?? getPrecision(stepSize);
  const steps = Math.floor(qty / stepSize + 1e-12);
  const stepped = steps * stepSize;
  return Number(stepped.toFixed(p));
}

/**
 * Formats a price to tickSize and precision without exponential notation.
 */
export function roundToTick(price: number, tickSize: number, precision?: number): number {
  if (!tickSize || tickSize <= 0) return price;
  const p = precision ?? getPrecision(tickSize);
  const ticks = Math.round(price / tickSize);
  const ticked = ticks * tickSize;
  return Number(ticked.toFixed(p));
}

/**
 * Formats a number to a string with exact precision, avoiding scientific notation (e.g. 1e-7).
 */
export function formatPrecisionString(val: number, precision: number): string {
  return val.toFixed(precision);
}

/**
 * Helper to sanitize raw HTTP error response bodies (especially multi-line HTML from CloudFront, WAF, or Nginx)
 * into a clean, concise single-line error message.
 */
export function sanitizeHttpErrorBody(status: number | string, text: string): string {
  if (!text) return `HTTP ${status}`;

  const isHtml =
    /<[a-z][\s\S]*>/i.test(text) ||
    text.includes("Generated by cloudfront") ||
    text.includes("<!DOCTYPE") ||
    text.includes("CloudFront");

  if (isHtml) {
    // Extract CloudFront Request ID if present
    const reqIdMatch = text.match(/Request ID:\s*([^<\r\n]+)/i);
    let reqId = "";
    if (reqIdMatch && reqIdMatch[1]) {
      reqId = reqIdMatch[1].replace(/&#x3D;/gi, "=").replace(/&amp;/gi, "&").trim();
    }

    // Try to extract meaningful headline
    const h1Match = text.match(/<H1>([^<]+)<\/H1>/i);
    const h2Match = text.match(/<H2>([^<]+)<\/H2>/i);
    const titleMatch = text.match(/<TITLE>([^<]+)<\/TITLE>/i);

    let summary = (h2Match?.[1] || h1Match?.[1] || titleMatch?.[1] || "The request could not be satisfied").trim();
    if (text.includes("Request blocked")) {
      summary = `Request blocked / ${summary}`;
    }

    if (text.toLowerCase().includes("cloudfront") || reqId) {
      return `CloudFront: ${summary}${reqId ? ` (Request ID: ${reqId})` : ""}`;
    }

    // Generic HTML cleanup: strip tags, decode common entities, collapse whitespace
    const cleanText = text
      .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, " ")
      .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, " ")
      .replace(/<[^>]+>/g, " ")
      .replace(/&#x3D;/gi, "=")
      .replace(/&amp;/gi, "&")
      .replace(/&lt;/gi, "<")
      .replace(/&gt;/gi, ">")
      .replace(/&quot;/gi, '"')
      .replace(/&#39;/gi, "'")
      .replace(/\s+/g, " ")
      .trim();

    return cleanText.slice(0, 120) + (cleanText.length > 120 ? "..." : "");
  }

  // Plain text / JSON message: collapse all newlines into single line
  const singleLine = text.replace(/[\r\n\t]+/g, " ").replace(/\s+/g, " ").trim();
  return singleLine.length > 200 ? singleLine.slice(0, 197) + "..." : singleLine;
}


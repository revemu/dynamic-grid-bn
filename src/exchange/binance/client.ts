  // ── User Data Stream (WebSocket ListenKey) ────────────────────────────────

  /**
   * Start a new user data stream and return the listenKey.
   * Requires API-KEY in header (public request, not signed with secret).
   */
  public async createUserDataStream(): Promise<string> {
    if (!this.apiKey) {
      throw new Error("Binance API key is required to create a user data stream");
    }
    // Try POST /api/v3/userDataStream first, fallback to /sapi/v1/userDataStream if 404/410
    try {
      const res = await this.publicRequest<{ listenKey?: string }>("POST", "/api/v3/userDataStream");
      if (res && res.listenKey) return res.listenKey;
    } catch (err: any) {
      if (String(err?.message || "").includes("410") || String(err?.message || "").includes("404")) {
        // Try fallback endpoint
        const res2 = await this.publicRequest<{ listenKey?: string }>("POST", "/sapi/v1/userDataStream");
        if (res2 && res2.listenKey) return res2.listenKey;
      }
      throw err;
    }
    throw new Error("Empty listenKey received from Binance User Data Stream");
  }

  /**
   * Keep-alive a user data stream to prevent timeout (must be called every 30 mins).
   */
  public async keepAliveUserDataStream(listenKey: string): Promise<void> {
    if (!this.apiKey) return;
    try {
      await this.rawRequest<any>("PUT", "/api/v3/userDataStream", { listenKey }, false);
    } catch {
      try {
        await this.rawRequest<any>("PUT", "/sapi/v1/userDataStream", { listenKey }, false);
      } catch {
        // Ignore keepalive failures
      }
    }
  }

  /**
   * Close a user data stream when shutting down.
   */
  public async closeUserDataStream(listenKey: string): Promise<void> {
    if (!this.apiKey) return;
    try {
      await this.rawRequest<any>("DELETE", "/api/v3/userDataStream", { listenKey }, false);
    } catch {
      try {
        await this.rawRequest<any>("DELETE", "/sapi/v1/userDataStream", { listenKey }, false);
      } catch {
        // Ignore errors when closing
      }
    }
  }

  // ── HTTP Request Core ─────────────────────────────────────────────────────

  private async publicRequest<T = any>(
    method: "GET" | "POST",
    path: string,
    params: Record<string, any> = {},
  ): Promise<T> {
    return this.rawRequest<T>(method, path, params, false);
  }

  private async signedRequest<T = any>(
    method: "GET" | "POST" | "DELETE",
    path: string,
    params: Record<string, any> = {},
  ): Promise<T> {
    return this.rawRequest<T>(method, path, params, true);
  }

  private async rawRequest<T = any>(
    method: "GET" | "POST" | "PUT" | "DELETE",
    path: string,
    params: Record<string, any> = {},
    signed = false,
    retryCount = 0,
  ): Promise<T> {
    const cleanParams: Record<string, string> = {};
    for (const [k, v] of Object.entries(params)) {
      if (v !== undefined && v !== null) {
        cleanParams[k] = String(v);
      }
    }

    if (signed) {
      if (!this.apiKey || !this.apiSecret) {
        throw new Error(
          `Binance API Key and Secret are required for signed endpoint: ${path}. Please configure BINANCE_API_KEY and BINANCE_API_SECRET in .env`,
        );
      }
      // Apply -50ms safety buffer so request timestamp is never ahead of Binance server clock
      // Binance strictly rejects any request where timestamp > serverTime as Error -1021.
      cleanParams.timestamp = String(Date.now() + this.timeOffset - 50);
      cleanParams.recvWindow = String(this.recvWindow);

      const queryString = new URLSearchParams(cleanParams).toString();
      const signature = crypto
        .createHmac("sha256", this.apiSecret)
        .update(queryString)
        .digest("hex");
      cleanParams.signature = signature;
    }

    const query = new URLSearchParams(cleanParams).toString();
    const url = `${this.baseUrl}${path}${query ? (path.includes("?") ? "&" : "?") + query : ""}`;

    const headers: Record<string, string> = {
      "User-Agent": "dynamic-grid-binance/1.0",
      Accept: "application/json",
    };
    if (this.apiKey) {
      headers["X-MBX-APIKEY"] = this.apiKey;
    }

    try {
      const res = await fetch(url, {
        method,
        headers,
      });

      const text = await res.text();
      let data: any;
      try {
        data = JSON.parse(text);
      } catch {
        const cleanMsg = sanitizeHttpErrorBody(res.status, text);
        throw new Error(`Binance HTTP ${res.status}: ${cleanMsg}`);
      }

      if (!res.ok || (data && typeof data.code === "number" && data.code < 0)) {
        // If timestamp outside recvWindow (-1021), resync time and retry once
        if (data?.code === -1021 && retryCount === 0) {
          this.log(`⚠️ Timestamp error (-1021) encountered. Re-syncing time with Binance server...`);
          await this.syncTime();
          return this.rawRequest<T>(method, path, params, signed, retryCount + 1);
        }

        const code = data?.code ?? res.status;
        const rawMsg = data?.msg ?? text;
        const msg = typeof rawMsg === "string" ? sanitizeHttpErrorBody(code, rawMsg) : rawMsg;

        if (res.status === 429 || res.status === 418 || code === -1003) {
          const retryAfter = res.headers.get("Retry-After");
          this.log(
            `🚨 [RATE LIMIT] Binance rate-limit / ban encountered (HTTP ${res.status}, code ${code}, Retry-After: ${retryAfter ?? "N/A"}): ${msg}`,
          );
        }

        throw new Error(`Binance Error [${code}]: ${msg}`);
      }

      return data as T;
    } catch (err) {
      throw err;
    }
  }

  public async getRecentOrders(symbol: string, limit = 50): Promise<ExchangeOpenOrder[]> {
    const sym = symbol.toUpperCase().replace(/[\/\-_:]/g, "");
    const raw = await this.signedRequest<any[]>("GET", "/api/v3/allOrders", {
      symbol: sym,
      limit: Math.min(500, Math.max(1, limit)),
    });
    return (raw || []).map((o) => ({
      symbol: o.symbol,
      orderId: Number(o.orderId),
      clientOrderId: o.clientOrderId,
      price: Number(o.price),
      origQty: Number(o.origQty),
      executedQty: Number(o.executedQty),
      cummulativeQuoteQty: Number(o.cummulativeQuoteQty),
      status: o.status,
      timeInForce: o.timeInForce,
      type: o.type,
      side: o.side,
      time: Number(o.time),
      updateTime: Number(o.updateTime),
      isWorking: Boolean(o.isWorking),
    }));
  }

    if (apiSecret !== undefined && apiSecret !== "******" && apiSecret.trim() !== "") this.apiSecret = apiSecret.trim();
    if (baseUrl !== undefined) this.baseUrl = baseUrl.trim().replace(/\/+$/, "");

function formatTimestamp(d = new Date()): string {
  try {
    const tz = config.timezone || process.env.TZ || "Asia/Bangkok";
    const formatter = new Intl.DateTimeFormat("sv-SE", {
      timeZone: tz,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
    const ms = String(d.getMilliseconds()).padStart(3, "0");
    return `${formatter.format(d)}.${ms}`;
  } catch {
    const pad = (n: number) => String(n).padStart(2, "0");
    const padMs = (n: number) => String(n).padStart(3, "0");
    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}.${padMs(d.getMilliseconds())}`;
  }
}

function log(msg: string, extra?: unknown): void {
  let cleanMsg = msg;
  if (
    typeof msg === "string" &&
    (msg.includes("Generated by cloudfront") ||
      msg.includes("<!DOCTYPE") ||
      msg.includes("<BODY>") ||
      msg.includes("</HTML>") ||
      msg.includes("<HTML>"))
  ) {
    cleanMsg = sanitizeHttpErrorBody("LOG", msg);
  }
  const line = `[dynamic-grid ${formatTimestamp()}] ${cleanMsg}`;
  if (extra !== undefined) console.log(line, extra);
  else console.log(line);
}

async function main(): Promise<void> {
  let exchange = createExchangeClient({
    exchange: config.exchange || "binance",
    apiKey: config.binanceApiKey,
    apiSecret: config.binanceApiSecret,
    baseUrl: config.binanceBaseUrl,
    privateKey: config.dreamdexPrivateKey,
    rpcUrl: config.dreamdexRpcUrl,
    log: (msg) => log(`[${config.exchange || "binance"}] ${msg}`),
  });

  await exchange.syncTime();

  let activeSymbol = (config.symbol || "BTCUSDT").toUpperCase().replace(/[\/\-_:]/g, "");
  let symbolInfo = await exchange.getExchangeInfo(activeSymbol);

  log(
    `📊 Spot Market (${exchange.exchangeName.toUpperCase()}): ${symbolInfo.symbol} (${symbolInfo.baseAsset}/${symbolInfo.quoteAsset}) ` +
      `| minQty: ${symbolInfo.minQty} | stepSize: ${symbolInfo.stepSize} | tickSize: ${symbolInfo.tickSize} | minNotional: $${symbolInfo.minNotional}`,
  );

  // ── Dow Theory & Market Structure Engines ────────────────────────────────
  // 1. Macro Engine (15m/1h): establishes the solid 0% Floor, 50% Center, 100% Ceiling
  const macroDowEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );
  // 2. Local Trend Engine (15m): detects localized downtrends to pause buys during drops
  const localTrendEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );
  // 3. HTF Anchor Engine (4h): establishes institutional macro support floor and ceiling
  const htfDowEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );

  // Preload macro candles, trading candles, and HTF candles on boot
  let macroFeed: BinanceAtrFeed | undefined;
  let tradingFeed: BinanceAtrFeed | undefined;
  let htfFeed: BinanceAtrFeed | undefined;
  let atrSource: AtrSource;

  let bookTickerFeed: BinanceBookTickerFeed | undefined;
  let userDataFeed: BinanceUserDataFeed | undefined;
  let dashboard: DashboardServer | null = null;

  // Map trading symbol (which may be on DreamDEX like SOMI, SOMI:USDSO, WBTC, WETH)
  // to a liquid Binance Spot Symbol for 100% reliable candlestick data & ATR calculations!
  const resolveBinanceCandleSymbol = (sym: string): string => {
    const s = sym.toUpperCase().replace(/[\/\-_:]/g, "");
    if (s.startsWith("SOMI")) return "SOMIUSDT";
    if (s.startsWith("USDC") || s === "USDSO") return "USDCUSDT";
    if (s.startsWith("WBTC") || s === "BTC") return "BTCUSDT";
    if (s.startsWith("WETH") || s === "ETH") return "ETHUSDT";
    // If symbol does not end with USDT, USDC, FDUSD, etc., default to appending USDT
    if (!s.endsWith("USDT") && !s.endsWith("USDC") && !s.endsWith("FDUSD")) {
      return `${s}USDT`;
    }
    return s;
  };

  const initFeeds = async (sym: string) => {
    const binanceCandleSymbol = resolveBinanceCandleSymbol(sym);
    const symLower = binanceCandleSymbol.toLowerCase();

    log(`📈 Initializing Binance market feeds for ${sym} -> using Binance symbol: ${binanceCandleSymbol}`);

    macroDowEngine.clearCandles();
    localTrendEngine.clearCandles();
    htfDowEngine.clearCandles();

    const isMaFan = config.strategyType === "ma_fan";
    const primaryInterval = isMaFan ? ((config.maFanExecutionTimeframe as string) || "5m") : config.dowTimeframe;
    const htfInterval = isMaFan ? ((config.maFanSupervisorTimeframe as string) || "15m") : config.htfTimeframe;

    await macroDowEngine.loadHigherTimeframeCandles(
      binanceCandleSymbol,
      primaryInterval,
      config.binanceBaseUrl,
      log,
      config.initialCandleCount ?? 300,
      true,
    );
    await localTrendEngine.loadHigherTimeframeCandles(
      binanceCandleSymbol,
      config.tradingTimeframe,
      config.binanceBaseUrl,
      log,
      config.initialCandleCount ?? 300,
      true,
    );
    await htfDowEngine.loadHigherTimeframeCandles(
      binanceCandleSymbol,
      htfInterval,
      config.binanceBaseUrl,
      log,
      300,
      true,
    );
    dashboard?.setInitialHtfCandles(htfDowEngine.getCandles());

    macroFeed?.stop();
    tradingFeed?.stop();
    htfFeed?.stop();
    bookTickerFeed?.stop();
    userDataFeed?.stop();

    macroFeed = new BinanceAtrFeed(
      {
        symbol: symLower,
        interval: primaryInterval,
        wsBase: config.binanceWsBase,
        staleMs: config.binanceStaleMs,
        initialCandleCount: config.initialCandleCount ?? 300,
      },
      config.atrLookback,
      (msg) => log(`[macro ${primaryInterval}] ${msg}`),
    );

    tradingFeed = new BinanceAtrFeed(
      {
        symbol: symLower,
        interval: config.tradingTimeframe,
        wsBase: config.binanceWsBase,
        staleMs: config.binanceStaleMs,
        initialCandleCount: config.initialCandleCount ?? 300,
      },
      config.atrLookback,
      (msg) => log(`[trading ${config.tradingTimeframe}] ${msg}`),
    );

    tradingFeed.onCandle((candle, isClosed) => {
      if (isClosed) {
        localTrendEngine.addCandle(candle);
      }
    });

    htfFeed = new BinanceAtrFeed(
      {
        symbol: symLower,
        interval: htfInterval,
        wsBase: config.binanceWsBase,
        staleMs: config.binanceStaleMs,
        initialCandleCount: 150,
      },
      config.atrLookback,
      (msg) => log(`[htf ${htfInterval}] ${msg}`),
    );

    htfFeed.onCandle((candle, isClosed) => {
      if (isClosed) {
        htfDowEngine.addCandle(candle);
        dashboard?.addHtfCandle(candle, isClosed);
        (grid as any).onHtfCandleClosed?.(candle);
      }
    });

    // 0-weight Real-Time Book Ticker WebSocket feed
    bookTickerFeed = new BinanceBookTickerFeed(
      symLower,
      config.binanceWsBase,
      (msg) => log(`[bookTicker] ${msg}`),
    );

    // Real-Time User Data Stream WebSocket feed (if on Binance with API credentials)
    if (exchange.exchangeName === "binance" && exchange.hasCredentials()) {
      userDataFeed = new BinanceUserDataFeed(
        {
          getCredentials: () => (exchange as any).getCredentials?.() ?? {
            apiKey: config.binanceApiKey,
            apiSecret: config.binanceApiSecret,
          },
          getTimeOffset: () => (exchange as any).getTimeOffset?.() ?? 0,
        },
        "wss://ws-api.binance.com:443/ws-api/v3",
        (msg) => log(`[userData] ${msg}`),
      );
    }

    atrSource = tradingFeed;
  };

  await initFeeds(symbolInfo.symbol);

  // Fetch initial balances
  let initialBaseBal = 0;
  let initialQuoteBal = 0;
  if (exchange.hasCredentials()) {
    try {
      const b = await exchange.getAccountBalances(symbolInfo.symbol);
      initialBaseBal = b.baseFree;
      initialQuoteBal = b.quoteFree;
    } catch (err) {
      log(`warning: failed to query initial ${exchange.exchangeName} balance: ${(err as Error).message}`);
    }
  } else {
    log(`ℹ️ Running without ${exchange.exchangeName} API credentials (public market data / dryRun mode).`);
  }

  log(
    `${exchange.exchangeName.toUpperCase()} Spot balance=[${initialBaseBal} ${symbolInfo.baseAsset} | ${initialQuoteBal.toFixed(2)} ${symbolInfo.quoteAsset}] ` +
      `symbol=${symbolInfo.symbol} maxInv=$${config.maxInventoryQuote} dryRun=${config.dryRun} ` +
      `trendFilter=${config.dowTrendFilter} (${config.trendTimeframe})`,
  );

  let grid: IStrategy = createStrategy(config.strategyType, {
    exchange,
    symbolInfo,
    config,
    atrSource: atrSource!,
    log,
    macroDowEngine,
    localTrendEngine,
    htfDowEngine,
  });
  await grid.syncOnChainOrders();
  await grid.refreshWalletBalances();

  // 🛡️ Safe Boot: Always ensure bot starts in PAUSED mode on startup across all strategies
  grid.setPaused(true);
  log("⏸️ [SAFE BOOT] Bot started in PAUSED mode as requested. Resume trading via dashboard or API.");

  let wakeSleep: (() => void) | null = null;
  const interruptibleSleep = (ms: number): Promise<void> => {
    return new Promise((resolve) => {
      let timer: NodeJS.Timeout | null = setTimeout(() => {
        wakeSleep = null;
        resolve();
      }, ms);
      wakeSleep = () => {
        if (timer) {
          clearTimeout(timer);
          timer = null;
        }
        wakeSleep = null;
        resolve();
      };
    });
  };

  const wireFeedsToGrid = () => {
    if (bookTickerFeed) {
      bookTickerFeed.onBook((b) => grid.handleWsBookTicker?.(b));
      bookTickerFeed.start();
    }
    if (userDataFeed) {
      userDataFeed.onExecutionReport((rep) => grid.handleWsExecutionReport?.(rep));
      userDataFeed.onAccountUpdate((acc) => grid.handleWsAccountUpdate?.(acc));
      userDataFeed.start().catch((err) => log(`⚠️ User data stream start error: ${(err as Error).message}`));
    }
  };

  // ── Real-Time Dashboard Server & Dynamic Config API ───────────────────────
  dashboard = new DashboardServer({
    port: config.dashboardPort,
    log,
    db: grid.getDatabase(),
    maxCandles: config.maxCandleCount ?? 600,
    getSettings: () => grid.getRuntimeConfig(),
    onUpdateSettings: async (s) => {
      const prevConfig = grid.getRuntimeConfig();
      const prevInitial = prevConfig.initialCandleCount;
      const prevMax = prevConfig.maxCandleCount;
      const prevTf = prevConfig.dowTimeframe;
      const prevTradingTf = prevConfig.tradingTimeframe;
      const prevHtfTf = prevConfig.htfTimeframe;
      const prevSymbol = prevConfig.symbol;

      const targetExchangeName = (s.exchange || prevConfig.exchange || "binance").toLowerCase();
      const exchangeChanged = Boolean(s.exchange && targetExchangeName !== (prevConfig.exchange || "binance").toLowerCase());
      const privateKeyChanged = s.dreamdexPrivateKey && s.dreamdexPrivateKey !== "******";

      const normPrevSymbol = (prevSymbol || "").toUpperCase().replace(/[\/\-_:]/g, "");
      let normNextSymbol = (s.symbol || "").toUpperCase().replace(/[\/\-_:]/g, "");

      // 🛡️ DreamDEX Accidental CEX Symbol Guard:
      // If running on DreamDEX and incoming symbol is an accidental CEX symbol (e.g. BTCUSDT, BTCFDUSD, ETHUSDT)
      // while user was trading SOMI/USDSO, ignore the accidental switch and preserve active SOMI pair!
      if (!exchangeChanged && targetExchangeName === "dreamdex" && (normNextSymbol === "BTCUSDT" || normNextSymbol === "BTCFDUSD" || normNextSymbol === "ETHUSDT" || normNextSymbol === "ETHFDUSD")) {
        if (normPrevSymbol.startsWith("SOMI") || !normPrevSymbol) {
          log(`🛡️ [SYMBOL GUARD] Ignored accidental CEX symbol '${normNextSymbol}' on DreamDEX; keeping active pair '${prevSymbol || "SOMI:USDSO"}'`);
          normNextSymbol = normPrevSymbol || "SOMIUSDSO";
          s.symbol = prevSymbol || "SOMI:USDSO";
        }
      }

      const symbolChanged = Boolean(normNextSymbol && normNextSymbol !== normPrevSymbol);

      // Lock Trading Pair & Exchange switch when bot holds an active position
      const isHoldingPosition = grid.baseHeld() > (symbolInfo?.minQty ?? 0.0001) || grid.getLots().length > 0;
      if ((symbolChanged || exchangeChanged) && isHoldingPosition) {
        const heldAmount = grid.baseHeld();
        const lotCount = grid.getLots().length;
        const baseName = symbolInfo?.baseAsset || "tokens";
        const errMsg = `Cannot switch trading pair or exchange while holding active position (${heldAmount.toFixed(4)} ${baseName} held across ${lotCount} lot(s)). Please exit or close position first.`;
        log(`⛔ [PAIR SWITCH BLOCKED] ${errMsg}`);
        throw new Error(errMsg);
      }

      const res = grid.updateRuntimeSettings(s);

      // 1. Handle Exchange Adapter switch or credentials update dynamically
      if (exchangeChanged || (targetExchangeName === "dreamdex" && privateKeyChanged)) {
        grid.setSwitchingSymbol(true);
        try {
          // If switching exchange or symbol, cancel all resting orders on the current exchange/pair first
          if (exchangeChanged || symbolChanged) {
            await grid.prepareForSymbolSwitch(normNextSymbol || targetExchangeName.toUpperCase());
          }

          const realPrivateKey = (s.dreamdexPrivateKey !== undefined && s.dreamdexPrivateKey !== "******" && s.dreamdexPrivateKey.trim() !== "")
            ? s.dreamdexPrivateKey.trim()
            : grid.getRealDreamdexPrivateKey();

          const realApiSecret = (s.binanceApiSecret !== undefined && s.binanceApiSecret !== "******")
            ? s.binanceApiSecret
            : grid.getRealBinanceApiSecret();

          const realApiKey = (s.binanceApiKey !== undefined && s.binanceApiKey !== "******")
            ? s.binanceApiKey
            : grid.getRealBinanceApiKey();

          const newExchange = createExchangeClient({
            exchange: targetExchangeName,
            apiKey: realApiKey,
            apiSecret: realApiSecret,
            baseUrl: s.binanceBaseUrl || prevConfig.binanceBaseUrl,
            privateKey: (realPrivateKey && realPrivateKey !== "******") ? realPrivateKey : undefined,
            rpcUrl: s.dreamdexRpcUrl || prevConfig.dreamdexRpcUrl,
            log: (msg) => log(`[${targetExchangeName}] ${msg}`),
          });
          await newExchange.syncTime();
          exchange = newExchange;

          // If switching to dreamdex and symbol is still a Binance symbol like ETHFDUSD, suggest/switch to SOMI
          let targetSymbol = (s.symbol || prevConfig.symbol || "BTCUSDT").toUpperCase().replace(/[\/\-_:]/g, "");
          if (targetExchangeName === "dreamdex" && (targetSymbol.includes("FDUSD") || targetSymbol.includes("USDT") || targetSymbol === "BTCUSDT")) {
            targetSymbol = "SOMI";
          }

          const nextInfo = await exchange.getExchangeInfo(targetSymbol);
          symbolInfo = nextInfo;
          await initFeeds(nextInfo.symbol);
          grid.updateExchangeClient(newExchange, nextInfo, atrSource!);
          wireFeedsToGrid();
          await grid.refreshWalletBalances();
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.resetState({ clearTrades: false });
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          wakeSleep?.();
          log(`🔄 Successfully switched Exchange Adapter to: ${exchange.exchangeName.toUpperCase()} (${nextInfo.symbol})`);
        } catch (err) {
          log(`⚠️ Failed to switch exchange adapter to ${targetExchangeName}: ${(err as Error).message}`);
        } finally {
          grid.setSwitchingSymbol(false);
        }
      } else if (symbolChanged) {
        // 2. Handle trading pair change dynamically on same exchange
        const nextSymbolStr = normNextSymbol;
        grid.setSwitchingSymbol(true);
        try {
          // Validate symbol on exchange first before cancelling existing orders
          const nextInfo = await exchange.getExchangeInfo(nextSymbolStr);
          // Cancel all resting orders on the old pair (and sweep any orphan quote-locking orders) before switching
          await grid.prepareForSymbolSwitch(nextInfo.symbol);
          symbolInfo = nextInfo;
          await initFeeds(nextInfo.symbol);
          grid.updateSymbolInfo(nextInfo, atrSource!);
          wireFeedsToGrid();
          // Immediately refresh unlocked wallet balances & open orders before the first tick on the new pair
          await grid.refreshWalletBalances();
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.resetState({ clearTrades: false });
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          wakeSleep?.();
          log(`🔄 Switched active ${exchange.exchangeName} trading pair to: ${nextInfo.symbol}`);
        } catch (err) {
          // Restore previous symbol in settings if getExchangeInfo failed
          if (prevSymbol) {
            grid.updateRuntimeSettings({ symbol: prevSymbol });
          }
          log(`⚠️ Failed to switch symbol to ${nextSymbolStr}: ${(err as Error).message}`);
          throw err;
        } finally {
          grid.setSwitchingSymbol(false);
        }
      }

      // 3. Handle Strategy Type switch dynamically (e.g. Dynamic Grid <-> Swing Trade <-> MA Fan)
      const nextStrat = s.strategyType || s.strategyMode;
      if (nextStrat && nextStrat !== prevConfig.strategyType) {
        log(`🔄 [STRATEGY SWITCH] Switching active strategy from ${prevConfig.strategyType || "dynamic_grid"} to ${nextStrat}...`);
        try {
          await grid.cancelAllOrdersUser();
          const targetStrategyType = nextStrat;
          const currentConfig = grid.getRuntimeConfig();
          const cleanS = { ...s };
          if (cleanS.binanceApiKey === "******") delete cleanS.binanceApiKey;
          if (cleanS.binanceApiSecret === "******") delete cleanS.binanceApiSecret;
          if (cleanS.dreamdexPrivateKey === "******") delete cleanS.dreamdexPrivateKey;
          const mergedConfig = {
            ...currentConfig,
            ...cleanS,
            strategyType: targetStrategyType,
            binanceApiKey: grid.getRealBinanceApiKey() || config.binanceApiKey,
            binanceApiSecret: grid.getRealBinanceApiSecret() || config.binanceApiSecret,
            dreamdexPrivateKey: grid.getRealDreamdexPrivateKey() || config.dreamdexPrivateKey,
          };
          config.strategyType = targetStrategyType;
          await initFeeds(symbolInfo.symbol);
          wireFeedsToGrid();
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          dashboard.setInitialHtfCandles(htfDowEngine.getCandles());

          grid = createStrategy(targetStrategyType, {
            exchange,
            symbolInfo,
            config: mergedConfig,
            atrSource: atrSource!,
            log,
            macroDowEngine,
            localTrendEngine,
            htfDowEngine,
          });
          grid.updateRuntimeSettings(s);
          grid.getDatabase().setSetting("strategyType", targetStrategyType);
          grid.onEvent((event) => {
            if (event.type === "tick") {
              dashboard.updateTick(event.data);
            } else if (event.type === "order") {
              dashboard.addOrder(event.data);
            } else if (event.type === "order_gas") {
              dashboard.updateOrderGas(event.data.txHash, event.data.gasFeeBase, event.data.gasFeeQuote);
            }
          });
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.setInitialOrders(grid.getRecentOrders());
          grid.emitTelemetryTick();
          log(`✅ [STRATEGY SWITCH] Active strategy is now: ${grid.name} (${grid.strategyType})`);
        } catch (stratErr) {
          log(`⚠️ Failed to switch strategy dynamically: ${(stratErr as Error).message}`);
        }
      }

      if (s.maxCandleCount && s.maxCandleCount !== prevMax) {
        dashboard.setMaxCandles(s.maxCandleCount);
        macroDowEngine.setMaxCandles(s.maxCandleCount);
        localTrendEngine.setMaxCandles(s.maxCandleCount);
        htfDowEngine.setMaxCandles(s.maxCandleCount);
      }

      // If initialCandleCount changed or timeframe changed, re-fetch candles & restart WebSocket kline feeds
      if (
        (s.initialCandleCount && s.initialCandleCount !== prevInitial) ||
        (s.dowTimeframe && s.dowTimeframe !== prevTf) ||
        (s.tradingTimeframe && s.tradingTimeframe !== prevTradingTf) ||
        (s.htfTimeframe && s.htfTimeframe !== prevHtfTf) ||
        (s.maFanExecutionTimeframe && s.maFanExecutionTimeframe !== config.maFanExecutionTimeframe) ||
        (s.maFanSupervisorTimeframe && s.maFanSupervisorTimeframe !== config.maFanSupervisorTimeframe)
      ) {
        if (config.strategyType === "ma_fan") {
          await initFeeds(symbolInfo.symbol);
          wireFeedsToGrid();
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          dashboard.setInitialHtfCandles(htfDowEngine.getCandles());
          macroFeed?.start();
          tradingFeed?.start();
          htfFeed?.start();
          return res;
        }
        const fetchLimit = s.initialCandleCount ?? res.initialCandleCount ?? 300;
        const tf = s.dowTimeframe ?? res.dowTimeframe ?? config.dowTimeframe;
        const microTf = s.tradingTimeframe ?? res.tradingTimeframe ?? config.tradingTimeframe ?? "5m";
        try {
          const candleSym = resolveBinanceCandleSymbol(symbolInfo.symbol);
          const symLower = candleSym.toLowerCase();

          if ((s.dowTimeframe && s.dowTimeframe !== prevTf) || (s.initialCandleCount && s.initialCandleCount !== prevInitial)) {
            await macroDowEngine.loadHigherTimeframeCandles(
              candleSym,
              tf,
              config.binanceBaseUrl,
              log,
              fetchLimit,
              true,
            );
            dashboard.setInitialCandles(macroDowEngine.getCandles());
            log(`🔄 Reloaded ${fetchLimit} candles (${tf}) following settings update`);

            macroFeed?.stop();
            macroFeed = new BinanceAtrFeed(
              {
                symbol: symLower,
                interval: tf,
                wsBase: config.binanceWsBase,
                staleMs: config.binanceStaleMs,
                initialCandleCount: fetchLimit,
              },
              config.atrLookback,
              (msg) => log(`[macro ${tf}] ${msg}`),
            );
            macroFeed.onCandle((candle, isClosed) => {
              macroDowEngine.addCandle(candle);
              dashboard.addCandle(candle, isClosed);
              if (isClosed) {
                grid.onCandleClosed(candle);
                wakeSleep?.();
              }
            });
            macroFeed.start();
          }

          if ((s.tradingTimeframe && s.tradingTimeframe !== prevTradingTf) || (s.initialCandleCount && s.initialCandleCount !== prevInitial)) {
            await localTrendEngine.loadHigherTimeframeCandles(
              candleSym,
              microTf,
              config.binanceBaseUrl,
              log,
              fetchLimit,
              true,
            );
            log(`🔄 Reloaded ${fetchLimit} micro candles (${microTf}) following settings update`);

            tradingFeed?.stop();
            tradingFeed = new BinanceAtrFeed(
              {
                symbol: symLower,
                interval: microTf,
                wsBase: config.binanceWsBase,
                staleMs: config.binanceStaleMs,
                initialCandleCount: fetchLimit,
              },
              config.atrLookback,
              (msg) => log(`[trading ${microTf}] ${msg}`),
            );
            tradingFeed.onCandle((candle, isClosed) => {
              if (isClosed) {
                localTrendEngine.addCandle(candle);
              }
            });
            tradingFeed.start();
            grid.atrSource = tradingFeed;
            log(`🔄 Re-subscribed WebSocket Kline streams to micro timeframe: ${microTf}`);
          }

          if (s.htfTimeframe && s.htfTimeframe !== prevHtfTf) {
            const htfTf = s.htfTimeframe ?? config.htfTimeframe;
            await htfDowEngine.loadHigherTimeframeCandles(
              candleSym,
              htfTf,
              config.binanceBaseUrl,
              log,
              300,
              true,
            );
            dashboard?.setInitialHtfCandles(htfDowEngine.getCandles());
            log(`🔄 Reloaded HTF candles (${htfTf}) following settings update`);

            htfFeed?.stop();
            htfFeed = new BinanceAtrFeed(
              {
                symbol: symLower,
                interval: htfTf,
                wsBase: config.binanceWsBase,
                staleMs: config.binanceStaleMs,
                initialCandleCount: 300,
              },
              config.atrLookback,
              (msg) => log(`[htf ${htfTf}] ${msg}`),
            );
            htfFeed.onCandle((candle, isClosed) => {
              if (isClosed) {
                htfDowEngine.addCandle(candle);
                dashboard?.addHtfCandle(candle, isClosed);
                (grid as any).onHtfCandleClosed?.(candle);
              }
            });
            htfFeed.start();
            log(`🔄 Re-subscribed WebSocket Kline streams to HTF timeframe: ${htfTf}`);
          }
        } catch (err) {
          log(`⚠️ Failed to reload candles on settings update: ${(err as Error).message}`);
        }
      }

      grid.emitTelemetryTick();
      wakeSleep?.();
      return grid.getRuntimeConfig();
    },
    onPauseBot: (paused) => grid.setPaused(paused),
    getIsPaused: () => grid.getIsPaused(),
    onCancelAll: () => grid.cancelAllOrdersUser(),
    onSellAll: () => grid.sellAllUser(),
    onResetBot: (opts) => grid.resetBotState(opts),
    onResetPosition: () => grid.resetPosition(),
    onReloadState: () => {
      grid.reloadState();
      grid.emitTelemetryTick();
    },
  });

  dashboard.setInitialCandles(macroDowEngine.getCandles());
  dashboard.setInitialHtfCandles(htfDowEngine.getCandles());
  dashboard.setInitialOrders(grid.getRecentOrders());
  dashboard.start();

  wireFeedsToGrid();

  if (macroFeed) {
    macroFeed.onCandle((candle, isClosed) => {
      macroDowEngine.addCandle(candle);
      dashboard.addCandle(candle, isClosed);
      if (isClosed) {
        grid.onCandleClosed(candle);
        wakeSleep?.();
      }
    });
    macroFeed.start();
  }
  tradingFeed?.start();

  // Forward strategy events (ticks, buy/sell/cut executions, gas updates) to dashboard
  grid.onEvent((event) => {
    if (event.type === "tick") {
      dashboard.updateTick(event.data);
    } else if (event.type === "order") {
      dashboard.addOrder(event.data);
    } else if (event.type === "order_gas") {
      dashboard.updateOrderGas(event.data.txHash, event.data.gasFeeBase, event.data.gasFeeQuote);
    }
  });

  let stop = false;
  process.on("SIGINT", () => {
    stop = true;
    wakeSleep?.();
    grid.saveState();
    log("stopping after current tick…");
  });
  process.on("SIGTERM", () => {
    stop = true;
    wakeSleep?.();
    grid.saveState();
  });

  while (!stop) {
    try {
      await grid.tick();
    } catch (err) {
      log("tick error", (err as Error).message);
    }
    const loopInterval = grid.getIntervalMs();
    await interruptibleSleep(loopInterval > 0 ? loopInterval : 1000);
  }

  dashboard.stop();
  macroFeed?.stop();
  tradingFeed?.stop();
  bookTickerFeed?.stop();
  userDataFeed?.stop();
  process.exit(0);
}

main().catch((err) => {
  console.error("[dynamic-grid] fatal:", err);
  process.exit(1);
});
